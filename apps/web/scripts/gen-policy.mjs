// Writes lib/policy.ts from docs/policy.md. The web image is built without docs/ (.dockerignore),
// so the page and the consent request take the policy from this generated module.
// Run from apps/web: `node scripts/gen-policy.mjs`; lib/policy.test.ts fails when they drift apart.
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("../../../docs/policy.md", import.meta.url);
const target = new URL("../lib/policy.ts", import.meta.url);

const markdown = readFileSync(source, "utf8");
const version = /^Версия: (\d{4}-\d{2}-\d{2})/m.exec(markdown)?.[1];
if (!version) throw new Error("docs/policy.md has no «Версия: YYYY-MM-DD» line");

writeFileSync(
  target,
  [
    "// Generated by scripts/gen-policy.mjs from docs/policy.md. Do not edit: change the policy and",
    "// run `node scripts/gen-policy.mjs`.",
    "",
    "/** `policy_version` of the consent in `POST /api/v1/workspaces`. */",
    `export const policyVersion = ${JSON.stringify(version)};`,
    "",
    "export const policyMarkdown =",
    `  ${JSON.stringify(markdown)};`,
    "",
  ].join("\n"),
);
