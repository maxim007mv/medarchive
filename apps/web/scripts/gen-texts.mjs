// Generates lib/texts.ts from docs/texts.md, the canonical UI text dictionary (TZ-frontend §0).
// Usage: `pnpm gen:texts`. lib/texts.test.ts fails when the two drift apart.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const DICTIONARY_PATH = fileURLToPath(new URL("../../../docs/texts.md", import.meta.url));
export const OUTPUT_PATH = fileURLToPath(new URL("../lib/texts.ts", import.meta.url));

const TEXT_ROW = /^\|\s*`([a-z][A-Za-z0-9]*(?:\.[A-Za-z0-9]+)+)`\s*\|\s*([^|]*?)\s*\|/;
const ERROR_ROW = /^\|\s*`([a-z_]+)`\s*\|\s*(\d{3})\s*\|\s*([^|]*?)\s*\|/;
// Plural table rows: word | one | few | many | where. Cells hold examples such as "2 документа".
const PLURAL_ROW = /^\|\s*([а-яё]+)\s*\|([^|]+)\|([^|]+)\|([^|]+)\|/;

/** The form of `word` used in an example cell: the token that shares the word's stem. */
function formFromExample(word, cell) {
  const stem = word.slice(0, 4);
  const example = cell.split(",")[0] ?? "";
  const form = example
    .trim()
    .split(/\s+/)
    .find((token) => token.toLowerCase().startsWith(stem));
  if (!form) throw new Error(`texts.md: no form of «${word}» in «${cell.trim()}»`);
  return form;
}

export function parseDictionary(markdown) {
  const texts = new Map();
  const errors = new Map();
  const plurals = new Map();
  let section = "";

  for (const line of markdown.split("\n")) {
    if (line.startsWith("## ")) {
      section = line;
      continue;
    }
    if (section.startsWith("## 2.")) {
      const plural = PLURAL_ROW.exec(line);
      if (plural) {
        const [, word = "", ...cells] = plural;
        plurals.set(
          word,
          cells.map((cell) => formFromExample(word, cell)),
        );
      }
      continue;
    }
    if (section.startsWith("## 16.")) {
      const error = ERROR_ROW.exec(line);
      if (error) errors.set(error[1], error[3]);
      continue;
    }
    const text = TEXT_ROW.exec(line);
    if (!text) continue;
    const [, key = "", value = ""] = text;
    if (texts.has(key)) throw new Error(`texts.md: duplicate key ${key}`);
    texts.set(key, value);
  }
  return { texts, errors, plurals };
}

const quote = (value) => JSON.stringify(value);

export function renderTexts(markdown) {
  const { texts, errors, plurals } = parseDictionary(markdown);
  const entries = (map, render) => [...map].map(([key, value]) => `  ${render(key, value)},`);

  return [
    "// Generated by scripts/gen-texts.mjs from docs/texts.md. Do not edit: change the dictionary",
    "// and run `pnpm gen:texts`.",
    "",
    "export const texts = {",
    ...entries(texts, (key, value) => `${quote(key)}: ${quote(value)}`),
    "} as const;",
    "",
    "/** `title` of each problem+json `code` (06-api-contract.md, section 8). */",
    "export const errorTitles = {",
    ...entries(errors, (key, value) => `${key}: ${quote(value)}`),
    "} as const;",
    "",
    "/** Forms for `plural()` from lib/format.ts: one, few, many. */",
    "export const plurals = {",
    ...entries(plurals, (key, forms) => `${key}: [${forms.map(quote).join(", ")}]`),
    "} as const;",
    "",
    "export type TextKey = keyof typeof texts;",
    "export type ErrorCode = keyof typeof errorTitles;",
    "",
    "type Placeholders<S extends string> = S extends `${string}{${infer Name}}${infer Rest}`",
    "  ? Name | Placeholders<Rest>",
    "  : never;",
    "type Params<K extends TextKey> = [Placeholders<(typeof texts)[K]>] extends [never]",
    "  ? []",
    "  : [params: Record<Placeholders<(typeof texts)[K]>, string | number>];",
    "",
    "/** Dictionary text with `{name}` placeholders filled; the key decides which params are required. */",
    "export function t<K extends TextKey>(key: K, ...[params]: Params<K>): string {",
    "  const values: Record<string, string | number> = params ?? {};",
    "  return texts[key].replace(/\\{([^{}]+)\\}/g, (placeholder, name: string) =>",
    "    String(values[name] ?? placeholder),",
    "  );",
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT_PATH, renderTexts(readFileSync(DICTIONARY_PATH, "utf8")));
}
